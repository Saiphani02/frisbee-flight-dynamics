%% =========================================================
%  AUTO-BUILD SIMULINK MODEL — Frisbee Flight Dynamics
%  Student : Sai Phanidhar Ammiraju
%  Course  : Flight Dynamics | Florida Atlantic University
%  Professor: Tom Lawrence
%
%  HOW TO RUN:
%    1. Open MATLAB (with Simulink)
%    2. Press F5 (Run)
%    3. Simulink model opens automatically
%    4. Press the green Play ▶ button in Simulink
%    5. After simulation, run the plotting code at the bottom
% =========================================================
clear; clc;

%% ── Launch Conditions ───────────────────────────────────
v0        = 22;               % launch speed [m/s]
angle_deg = 15;               % launch angle [degrees]
spin_rpm  = 600;              % spin rate [RPM]

angle  = deg2rad(angle_deg);
spin   = spin_rpm * 2*pi/60;  % rad/s
vx0    = v0 * cos(angle);
vz0    = v0 * sin(angle);

% Initial state vector [x; y; z; vx; vy; vz; phi; theta; dphi; dtheta]
state0 = [0; 0; 1.5; vx0; 0; vz0; 0; angle; 0; 0];

%% ── Create / Reset Model ────────────────────────────────
mdl = 'frisbee_model';
if bdIsLoaded(mdl), close_system(mdl, 0); end
if exist([mdl '.slx'],'file'), delete([mdl '.slx']); end

new_system(mdl);
open_system(mdl);

set_param(mdl, ...
    'Solver',     'ode45', ...
    'SolverType', 'Variable-step', ...
    'StopTime',   '20', ...
    'RelTol',     '1e-6', ...
    'AbsTol',     '1e-8');

fprintf('Building Simulink model: %s\n', mdl);

%% ═══════════════════════════════════════════════════════
%  ARCHITECTURE:
%
%   [Spin Const] ──┐
%                  ├──► [Mux 11x1] ──► [MATLAB Fn: EOM]
%   [Integrator] ──┘         ▲              │ dstate
%      (state)                │              ▼
%         ▲                   └────── [Integrator 10x1]
%         │                                  │
%         └──────── state ───────────────────┘
%                                            │
%                                         [Demux]
%                                         /     \
%                                   [Scope X] [Scope Z]
%                                   [ToWS x]  [ToWS z]
% ═══════════════════════════════════════════════════════

%% ── Block: Spin Rate Constant ───────────────────────────
add_block('simulink/Sources/Constant', [mdl '/Spin_Rate'], ...
    'Position', [30 310 130 340], ...
    'Value',    num2str(spin));

%% ── Block: Mux (combine state + spin → 11 elements) ────
add_block('simulink/Signal Routing/Mux', [mdl '/State_Mux'], ...
    'Position', [180 160 210 350], ...
    'Inputs',   '2');

%% ── Block: MATLAB Function (Equations of Motion) ────────
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [mdl '/Frisbee_EOM'], ...
    'Position', [270 200 470 310]);

%% ── Block: Vector Integrator (state derivative → state) ─
IC_str = mat2str(state0);
add_block('simulink/Continuous/Integrator', [mdl '/State_Integrator'], ...
    'Position',        [550 200 630 310], ...
    'InitialCondition', IC_str);

%% ── Block: Demux (extract individual states) ─────────────
add_block('simulink/Signal Routing/Demux', [mdl '/State_Demux'], ...
    'Position', [680 165 700 345], ...
    'Outputs',  '10');

%% ── Blocks: Scopes ───────────────────────────────────────
add_block('simulink/Sinks/Scope', [mdl '/Scope_Range_X'], ...
    'Position', [760 165 800 195]);
add_block('simulink/Sinks/Scope', [mdl '/Scope_Height_Z'], ...
    'Position', [760 215 800 245]);

%% ── Blocks: To Workspace (save results for plotting) ─────
add_block('simulink/Sinks/To Workspace', [mdl '/X_out'], ...
    'Position',     [760 265 850 290], ...
    'VariableName', 'x_sim', ...
    'SampleTime',   '-1', ...
    'SaveFormat',   'Array');
add_block('simulink/Sinks/To Workspace', [mdl '/Z_out'], ...
    'Position',     [760 305 850 330], ...
    'VariableName', 'z_sim', ...
    'SampleTime',   '-1', ...
    'SaveFormat',   'Array');

%% ═══════════════════════════════════════════════════════
%  CONNECT ALL BLOCKS
%  NOTE: add_line uses RELATIVE block names (no model prefix)
% ═══════════════════════════════════════════════════════

% State_Integrator output → Mux input 1  (state feedback)
add_line(mdl, 'State_Integrator/1', 'State_Mux/1', 'autorouting','on');

% Spin_Rate constant → Mux input 2
add_line(mdl, 'Spin_Rate/1', 'State_Mux/2', 'autorouting','on');

% Mux output → MATLAB Function input
add_line(mdl, 'State_Mux/1', 'Frisbee_EOM/1', 'autorouting','on');

% MATLAB Function output (dstate) → Integrator input
add_line(mdl, 'Frisbee_EOM/1', 'State_Integrator/1', 'autorouting','on');

% Integrator output (state) → Demux
add_line(mdl, 'State_Integrator/1', 'State_Demux/1', 'autorouting','on');

% Demux outputs: 1=x, 3=z  → Scopes and To Workspace
add_line(mdl, 'State_Demux/1', 'Scope_Range_X/1',  'autorouting','on');
add_line(mdl, 'State_Demux/3', 'Scope_Height_Z/1', 'autorouting','on');
add_line(mdl, 'State_Demux/1', 'X_out/1', 'autorouting','on');
add_line(mdl, 'State_Demux/3', 'Z_out/1', 'autorouting','on');

fprintf('✓ All blocks connected.\n');

%% ═══════════════════════════════════════════════════════
%  SET THE EOM FUNCTION CODE INSIDE THE MATLAB FUNCTION BLOCK
% ═══════════════════════════════════════════════════════
rt     = sfroot();
m_obj  = rt.find('-isa','Simulink.BlockDiagram','Name', mdl);
charts = m_obj.find('-isa','Stateflow.EMChart');

eom_code = [
'function dstate = Frisbee_EOM(u)\n'...
'%% Frisbee Equations of Motion\n'...
'%  Input u: [state(10x1); spin] — 11 elements total\n'...
'%  Output dstate: [dx;dy;dz;dvx;dvy;dvz;dphi;dtheta;d2phi;d2theta]\n'...
'\n'...
'% Unpack inputs\n'...
'state = u(1:10);\n'...
'spin  = u(11);\n'...
'\n'...
'x     = state(1); y     = state(2);  z      = state(3);\n'...
'vx    = state(4); vy    = state(5);  vz     = state(6);\n'...
'phi   = state(7); theta = state(8);\n'...
'dphi  = state(9); dtheta= state(10);\n'...
'\n'...
'% Physical parameters\n'...
'm   = 0.175;  R = 0.107;  A = pi*R^2;  rho = 1.225;  g = 9.81;\n'...
'CL0 =  0.10;  CLa =  1.80;\n'...
'CD0 =  0.08;  CDa =  2.72;\n'...
'Cm0 =  0.01;  Cma = -0.40;  Cmq = -0.005;\n'...
'Izz = 0.5*m*R^2;  Ixx = 0.25*m*R^2;\n'...
'\n'...
'% Airspeed\n'...
'V = sqrt(vx^2 + vy^2 + vz^2);\n'...
'if V < 1e-6, V = 1e-6; end\n'...
'\n'...
'% Aerodynamic coefficients\n'...
'alpha = theta;\n'...
'q_dyn = 0.5 * rho * V^2;\n'...
'CL = CL0 + CLa * alpha;\n'...
'CD = CD0 + CDa * alpha^2;\n'...
'Lf = q_dyn * A * CL;\n'...
'Df = q_dyn * A * CD;\n'...
'\n'...
'% Force components\n'...
'vxy = sqrt(vx^2 + vy^2);\n'...
'lift_x = -Lf * (vz/V) * cos(phi);\n'...
'lift_y = -Lf * (vz/V) * sin(phi);\n'...
'lift_z =  Lf * (vxy/V) * cos(phi);\n'...
'drag_x = -Df * vx/V;\n'...
'drag_y = -Df * vy/V;\n'...
'drag_z = -Df * vz/V;\n'...
'\n'...
'% Translational accelerations\n'...
'ax = (lift_x + drag_x) / m;\n'...
'ay = (lift_y + drag_y) / m;\n'...
'az = (lift_z + drag_z) / m - g;\n'...
'\n'...
'% Pitching moment\n'...
'M_pitch = q_dyn*A*(2*R)*(Cm0 + Cma*alpha + Cmq*(dtheta*R/V));\n'...
'\n'...
'% Rotational accelerations (with gyroscopic coupling)\n'...
'd2phi   = (M_pitch - Izz*spin*dtheta) / Ixx;\n'...
'd2theta = (M_pitch + Izz*spin*dphi  ) / Ixx;\n'...
'\n'...
'% Output: state derivative vector\n'...
'dstate = [vx; vy; vz; ax; ay; az; dphi; dtheta; d2phi; d2theta];\n'...
'end\n'
];

if ~isempty(charts)
    charts(1).Script = sprintf(eom_code);
    fprintf('✓ EOM function code written to MATLAB Function block.\n');
else
    fprintf('⚠ Could not write EOM code automatically.\n');
    fprintf('  See instructions below to add it manually.\n');
end

%% ── Save model ───────────────────────────────────────────
save_system(mdl, [mdl '.slx']);
fprintf('\n✓ Model saved as: %s.slx\n', mdl);

%% ═══════════════════════════════════════════════════════
fprintf('\n════════════════════════════════════════════════\n');
fprintf('  MODEL READY — HOW TO RUN IT:\n');
fprintf('════════════════════════════════════════════════\n');
fprintf('  1. In the Simulink window, press the ▶ Play button\n');
fprintf('  2. Wait for simulation to complete\n');
fprintf('  3. Double-click Scope_Range_X → see X vs time\n');
fprintf('  4. Double-click Scope_Height_Z → see Z (height) vs time\n');
fprintf('  5. Then run THIS CODE in MATLAB command window:\n\n');
fprintf('     figure;\n');
fprintf('     plot(x_sim, max(z_sim,0), ''b-'', ''LineWidth'', 2);\n');
fprintf('     xlabel(''Horizontal Range (m)'');\n');
fprintf('     ylabel(''Height (m)'');\n');
fprintf('     title(''Frisbee Trajectory — Simulink (22 m/s, 15 deg, 600 RPM)'');\n');
fprintf('     grid on;\n');
fprintf('════════════════════════════════════════════════\n\n');
